    @pytest.mark.asyncio
    async def test_load_image_http(self):
        """Test loading image from HTTP URL."""
        test_url = "http://example.com/image.png"
        test_content = b"fake image content"
        
        # Mock httpx response
        mock_response = MagicMock()
        mock_response.content = test_content
        mock_response.raise_for_status = MagicMock()
        
        mock_client = MagicMock()
        mock_client.__aenter__ = AsyncMock(return_value=mock_client)
        mock_client.__aexit__ = AsyncMock(return_value=None)
        mock_client.get = AsyncMock(return_value=mock_response)
        
        with patch('httpx.AsyncClient', return_value=mock_client):
            result = await self.generator._load_image(test_url)
        
        assert result == test_content
        mock_client.get.assert_called_once_with(test_url, timeout=30)
    
    @pytest.mark.asyncio
    async def test_load_image_file(self):
        """Test loading image from file path."""
        test_content = b"fake image content"
        
        with tempfile.NamedTemporaryFile(delete=False) as temp_file:
            temp_file.write(test_content)
            temp_file.flush()
            temp_path = temp_file.name
        
        try:
            result = await self.generator._load_image(temp_path)
            assert result == test_content
        finally:
            os.unlink(temp_path)
    
