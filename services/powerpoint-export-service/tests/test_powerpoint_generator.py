    @pytest.mark.asyncio
    async def test_get_job_status(self):
        """Test job status tracking."""
        job_id = 123
        
        # Initially no status
        status = await self.generator.get_job_status(job_id)
        assert status is None
        
        # Simulate active job
        async with self.generator._lock:
            self.generator.active_jobs[job_id] = {
                "status": JobStatus.PROCESSING,
                "start_time": 1000,
                "current_slide": 1,
                "total_slides": 5
            }
        
        # Mock time.time to return predictable value
        with patch('time.time', return_value=1010):  # 10 seconds later
            status = await self.generator.get_job_status(job_id)
        
        assert status is not None
        assert status["job_id"] == job_id
        assert status["status"] == JobStatus.PROCESSING.value
        assert status["current_slide"] == 1
        assert status["total_slides"] == 5
        assert status["runtime_seconds"] == 10
        assert status["progress_percentage"] == 20.0  # 1/5 * 100
    
